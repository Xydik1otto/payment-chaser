function t(key) {
  return (I18N[currentLang()] && I18N[currentLang()][key]) || I18N.uk[key] || key;
}

function currentLang() {
  if (localStorage.getItem('chaser_lang')) return localStorage.getItem('chaser_lang');
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('uk') ? 'uk' : 'en';  // auto-detect browser language
}

function applyLang(lang) {
  if (!I18N[lang]) lang = 'uk';
  localStorage.setItem('chaser_lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const ph = t(el.dataset.i18nPh);
    if (el.dataset.i18nDynamic !== '1') el.placeholder = ph;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  const sw = document.getElementById('langSwitch');
  if (sw) sw.value = lang;
}
